defmodule AtpClient.SystemOnTptp.Systems do
  @moduledoc """
  Stateful `Agent` holding the systems a SystemOnTPTP deployment offers, as
  `AtpClient.System` records.

  The agent starts from the snapshot shipped with the library,
  `priv/system_on_tptp/systems.json`, so `resolve/2` and `systems/1` answer at
  once. With `config :atp_client, :sotptp, auto_refresh: true` (the default) a
  background refresh — the two requests of `AtpClient.SystemOnTptp.SystemInfo` —
  replaces the state when it succeeds; when it fails a warning is logged and the
  snapshot stays. `refresh/1` is the same refresh on demand, and
  `snapshot_age/0` says when what is loaded was generated.

  The snapshot is regenerated by `mix atp_client.systems.refresh`; the nightly
  workflow keeps it current.

  ## Names and identifiers

  SystemOnTPTP identifies a system as `<name>---<version>`, `Vampire---5.0.1`,
  and keeps only the current version of each. `resolve/2` accepts either form:
  an identifier is checked against the advertised list, and a bare name is
  resolved to the latest version advertised under it, so a caller writes
  `"Vampire"` and is not tied to a version string that changes under them.

  When the agent is not running nothing is loaded, and `resolve/2` passes
  identifiers through unchanged, since it has nothing to check them against.
  """
  use Agent

  require Logger

  alias AtpClient.Config
  alias AtpClient.System
  alias AtpClient.SystemOnTptp.SystemInfo

  @snapshot "system_on_tptp/systems.json"

  @typedoc "What the agent holds."
  @type state :: %{
          systems: [System.t()],
          generated_at: DateTime.t() | nil,
          source: binary() | nil
        }

  @typedoc "A filter for `systems/1`."
  @type filter ::
          {:capability, System.capability()}
          | {:interface, System.interface()}
          | {:spc, binary()}
          | {:name, binary()}

  @doc """
  Starts the agent from the snapshot and, when `auto_refresh` is set, schedules a
  background refresh.
  """
  @spec start_link(any()) :: {:ok, pid()} | {:error, any()}
  def start_link(_args) do
    with {:ok, pid} <- Agent.start_link(&load_snapshot/0, name: __MODULE__) do
      if Config.fetch(:sotptp, :auto_refresh, true), do: Task.start(&refresh_or_warn/0)
      {:ok, pid}
    end
  end

  defp refresh_or_warn do
    case refresh() do
      :ok ->
        :ok

      {:error, reason} ->
        Logger.warning(
          "#{inspect(__MODULE__)}: refresh failed, keeping the snapshot: #{inspect(reason)}"
        )
    end
  end

  @doc """
  Fetches the SystemInfo report and replaces the state with it.

  ## Options

    * `:url` — SystemOnTPTP endpoint (defaults to the configured URL);
    * `:refresh_timeout_ms` — receive timeout per request.
  """
  @spec refresh(keyword()) :: :ok | {:error, term()}
  def refresh(opts \\ []) do
    case SystemInfo.fetch(opts) do
      {:ok, [_ | _] = systems, _warnings} ->
        state = %{
          systems: systems,
          generated_at: DateTime.utc_now(:second),
          source: Config.fetch!(:sotptp, :url, opts)
        }

        Agent.update(__MODULE__, fn _ -> state end)

      {:ok, [], _warnings} ->
        {:error, :no_systems}

      {:error, _} = error ->
        error
    end
  end

  @doc """
  The systems loaded, filtered.

    * `capability:` — `AtpClient.System.capabilities/1` has it;
    * `interface:` — offered through it;
    * `spc:` — the record lists that SPC word exactly;
    * `name:` — the system's name.

  Returns `[]` when the agent is not running.
  """
  @spec systems([filter()]) :: [System.t()]
  def systems(filters \\ []) do
    Enum.filter(loaded().systems, fn system -> Enum.all?(filters, &keep?(system, &1)) end)
  end

  defp keep?(system, {:capability, capability}),
    do: Map.has_key?(System.capabilities(system), capability)

  defp keep?(system, {:interface, interface}), do: interface in system.interfaces
  defp keep?(system, {:spc, spc}), do: spc in (system.spcs || [])
  defp keep?(system, {:name, name}), do: system.name == name

  @doc """
  The identifiers of every system loaded.
  """
  @spec ids() :: [binary()]
  def ids, do: Enum.map(loaded().systems, & &1.id)

  @doc """
  The record for an identifier or name, resolved as `resolve/2` does; `nil` when
  there is none.
  """
  @spec get(binary()) :: System.t() | nil
  def get(system) when is_binary(system) do
    with {:ok, id} <- resolve(system),
         %System{} = found <- Enum.find(loaded().systems, &(&1.id == id)) do
      found
    else
      _otherwise -> nil
    end
  end

  @doc """
  What `AtpClient.Verdict` reads `system`'s output with: the record's `Solved`
  and `GaveUp` patterns, when it is loaded, and the name whose prover-specific
  messages apply (`:system_name`). `[]` for `nil`.
  """
  @spec verdict_options(binary() | nil) :: keyword()
  def verdict_options(nil), do: []

  def verdict_options(system) when is_binary(system) do
    case get(system) do
      %System{} = found ->
        [solved: found.solved, gave_up: Map.values(found.raw.gave_up), system_name: found.name]

      nil ->
        [system_name: system]
    end
  end

  @doc """
  When the systems loaded were generated, and where from: the snapshot's
  `generated_at`, or the time of the last successful refresh.
  """
  @spec snapshot_age() :: DateTime.t() | nil
  def snapshot_age, do: loaded().generated_at

  @doc """
  The name of a system identifier: `"Vampire"` for `"Vampire---5.0.1"`.

      iex> AtpClient.SystemOnTptp.Systems.name("Vampire---5.0.1")
      "Vampire"
  """
  @spec name(String.t()) :: String.t()
  defdelegate name(system), to: System

  @doc """
  Resolves a system name or identifier against the advertised systems.

  An identifier (`"E---3.5.1"`) must be advertised as written. A bare name
  (`"E"`) resolves to the latest version advertised under it, versions being
  compared component-wise as numbers. When no list is available — the agent is
  not running — an identifier is passed through unchanged and a bare name cannot
  be resolved.

      iex> systems = ["E---3.5.1", "Vampire---5.0.1", "Vampire---4.8", "TPTP4X---0.0"]
      iex> AtpClient.SystemOnTptp.Systems.resolve("Vampire", systems)
      {:ok, "Vampire---5.0.1"}
      iex> AtpClient.SystemOnTptp.Systems.resolve("Vampire---4.8", systems)
      {:ok, "Vampire---4.8"}
      iex> AtpClient.SystemOnTptp.Systems.resolve("Vampire---4.7", systems)
      {:error, {:unknown_system, "Vampire---4.7"}}
      iex> AtpClient.SystemOnTptp.Systems.resolve("Nope", systems)
      {:error, {:unknown_system, "Nope"}}
      iex> AtpClient.SystemOnTptp.Systems.resolve("Nope---1", [])
      {:ok, "Nope---1"}
  """
  @spec resolve(String.t(), [String.t()]) ::
          {:ok, String.t()} | {:error, {:unknown_system, String.t()}}
  def resolve(system, systems \\ ids()) when is_binary(system) and is_list(systems) do
    cond do
      system in systems -> {:ok, system}
      systems == [] and String.contains?(system, "---") -> {:ok, system}
      String.contains?(system, "---") -> {:error, {:unknown_system, system}}
      true -> latest(system, systems)
    end
  end

  @spec latest(String.t(), [String.t()]) ::
          {:ok, String.t()} | {:error, {:unknown_system, String.t()}}
  defp latest(name, systems) do
    case Enum.filter(systems, &(name(&1) == name)) do
      [] -> {:error, {:unknown_system, name}}
      versions -> {:ok, Enum.max_by(versions, &version_key/1)}
    end
  end

  # "5.0.1" sorts after "4.8" and "2.1.9999" after "2.1.10": each component is
  # compared as a number where it is one, and as text otherwise.
  @spec version_key(String.t()) :: [tuple()]
  defp version_key(system) do
    case String.split(system, "---", parts: 2) do
      [_name, version] -> version |> String.split(".") |> Enum.map(&component/1)
      [_name] -> []
    end
  end

  defp component(text) do
    case Integer.parse(text) do
      {number, rest} -> {1, number, rest}
      :error -> {0, 0, text}
    end
  end

  @spec loaded() :: state()
  defp loaded do
    if Process.whereis(__MODULE__),
      do: Agent.get(__MODULE__, & &1),
      else: %{systems: [], generated_at: nil, source: nil}
  end

  @doc """
  The path of the snapshot shipped with the library.
  """
  @spec snapshot_path() :: Path.t()
  def snapshot_path, do: :atp_client |> Application.app_dir("priv") |> Path.join(@snapshot)

  @doc """
  Reads a snapshot file; an absent or unreadable one is an empty state.
  """
  @spec read_snapshot(Path.t()) :: state()
  def read_snapshot(path) do
    with {:ok, text} <- File.read(path),
         {:ok, %{"systems" => systems} = snapshot} <- Jason.decode(text) do
      generated_at =
        case DateTime.from_iso8601(Map.get(snapshot, "generated_at", "")) do
          {:ok, datetime, _offset} -> datetime
          {:error, _} -> nil
        end

      %{
        systems: Enum.map(systems, &System.from_json/1),
        generated_at: generated_at,
        source: Map.get(snapshot, "source")
      }
    else
      _otherwise -> %{systems: [], generated_at: nil, source: nil}
    end
  end

  @doc """
  Encodes a state as a snapshot file: the records sorted by identifier, every
  object's keys sorted, so that a regenerated snapshot diffs line by line.
  """
  @spec encode_snapshot(state()) :: iodata()
  def encode_snapshot(%{systems: systems} = state) do
    %{
      "generated_at" => state.generated_at && DateTime.to_iso8601(state.generated_at),
      "source" => state.source,
      "count" => length(systems),
      "systems" => systems |> Enum.sort_by(&String.downcase(&1.id)) |> Enum.map(&System.to_json/1)
    }
    |> ordered()
    |> Jason.encode_to_iodata!(pretty: true)
  end

  defp ordered(map) when is_map(map) and not is_struct(map) do
    map
    |> Enum.sort_by(&elem(&1, 0))
    |> Enum.map(fn {key, value} -> {key, ordered(value)} end)
    |> Jason.OrderedObject.new()
  end

  defp ordered(list) when is_list(list), do: Enum.map(list, &ordered/1)
  defp ordered(value), do: value

  defp load_snapshot, do: read_snapshot(snapshot_path())

  @doc """
  The `SYSTEMS.md` table: one row per system, sorted by name, with its
  capabilities (`*` marks one from the `UserNote` fallback, `†` one from the
  overrides file), interfaces, SPCs and URL.
  """
  @spec markdown(state(), %{binary() => System.override()}) :: iodata()
  def markdown(%{systems: systems} = state, overrides \\ System.overrides()) do
    rows =
      systems
      |> Enum.sort_by(&{String.downcase(&1.name), &1.id})
      |> Enum.map(fn system ->
        capabilities =
          system
          |> System.capabilities(overrides)
          |> Enum.sort()
          |> Enum.map_join(", ", fn {capability, provenance} ->
            "#{capability}#{mark(provenance)}"
          end)

        cells = [
          "`#{system.id}`",
          capabilities,
          Enum.map_join(system.interfaces, ", ", &Atom.to_string/1),
          Enum.join(system.spcs || [], " "),
          system.url || ""
        ]

        ["| ", Enum.map_join(cells, " | ", &cell/1), " |\n"]
      end)

    [
      "# SystemOnTPTP systems\n\n",
      "Generated by `mix atp_client.systems.refresh` from #{state.source} at ",
      "#{state.generated_at && DateTime.to_iso8601(state.generated_at)}; #{length(systems)} systems.\n",
      "Capabilities: unmarked from the rules, `*` from the UserNote fallback, ",
      "`†` from `overrides.json`.\n\n",
      "| System | Capabilities | Interfaces | SPCs | URL |\n",
      "|---|---|---|---|---|\n",
      rows
    ]
  end

  defp mark(:rule), do: ""
  defp mark(:note), do: "*"
  defp mark(:override), do: "†"

  defp cell(text), do: String.replace(text, "|", "\\|")

  @doc """
  The difference between two sets of systems as a one-line summary:
  `+Vampire---5.1.0 −Vampire---5.0.1, 2 fields changed`.
  """
  @spec delta([System.t()], [System.t()]) :: binary()
  def delta(before, now) do
    old = Map.new(before, &{&1.id, System.to_json(&1)})
    new = Map.new(now, &{&1.id, System.to_json(&1)})
    added = new |> Map.keys() |> Enum.reject(&Map.has_key?(old, &1)) |> Enum.sort()
    removed = old |> Map.keys() |> Enum.reject(&Map.has_key?(new, &1)) |> Enum.sort()

    changed =
      for {id, fields} <- new,
          previous = old[id],
          {key, value} <- fields,
          previous[key] != value,
          reduce: 0,
          do: (count -> count + 1)

    words = Enum.map(added, &("+" <> &1)) ++ Enum.map(removed, &("−" <> &1))
    fields = "#{changed} field#{if changed == 1, do: "", else: "s"} changed"

    case words do
      [] -> fields
      words -> Enum.join(words, " ") <> ", " <> fields
    end
  end
end
